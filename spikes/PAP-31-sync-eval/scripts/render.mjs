#!/usr/bin/env node
/**
 * PAP-31: score the rubric and render the results table.
 *
 *   node scripts/render.mjs            # writes results/summary.json and results/table.md
 *   node scripts/render.mjs --check    # fails if the committed files are stale
 *
 * No dependencies: runs on plain Node 22, outside the pnpm workspace.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => JSON.parse(readFileSync(join(root, p), 'utf8'));

const rubric = read('rubric.json');
const citations = read('citations.json');
const measurements = read('measurements.json');
const engines = readdirSync(join(root, 'scores'))
  .filter((f) => f.endsWith('.json'))
  .map((f) => read(join('scores', f)));

const ORDER = ['electric-pglite', 'powersync', 'zero', 'replicache', 'baseline-tanstack-outbox'];
engines.sort((a, b) => ORDER.indexOf(a.engine) - ORDER.indexOf(b.engine));

function scoreEngine(e) {
  let total = 0;
  const missing = [];
  for (const c of rubric.criteria) {
    const s = e.scores[c.id];
    if (!s) throw new Error(`${e.engine}: no score for ${c.id}`);
    if (!s.cite) throw new Error(`${e.engine}: score ${c.id} has no citation`);
    for (const key of s.cite.split(',')) {
      if (!citations[key.trim()]) throw new Error(`${e.engine}/${c.id}: unknown citation "${key}"`);
    }
    if (c.hard && s.score === 0) missing.push(c.id);
    total += (s.score / 5) * c.weight;
  }
  return { total: +total.toFixed(1), hardFails: missing };
}

const cell = (v, unit) => (v === null || v === undefined ? 'n/m' : `${v} ${unit}`);

const summary = engines.map((e) => {
  const { total, hardFails } = scoreEngine(e);
  const m = measurements.engines[e.engine] ?? { measured: false };
  return {
    engine: e.engine,
    label: e.label,
    versions: e.versions,
    licence: e.licence,
    measured: m.measured === true,
    measurementScope: m.scope ?? null,
    notMeasuredReason: m.reason ?? null,
    initialSyncMs: m.initialSyncMs ?? null,
    incrementalP50Ms: m.incrementalP50Ms ?? null,
    incrementalP95Ms: m.incrementalP95Ms ?? null,
    replay200Ms: m.replay200Ms ?? null,
    heapMb: m.heapMb ?? null,
    coldStartMs: m.coldStartMs ?? null,
    score: total,
    hardFails,
  };
});

const lines = [];
lines.push('<!-- generated by scripts/render.mjs; do not edit by hand -->');
lines.push('');
lines.push('## Rubric scores (0-5 per criterion, weighted to 100)');
lines.push('');
lines.push(`| Criterion | Weight | ${engines.map((e) => e.label).join(' | ')} |`);
lines.push(`| --- | ---: | ${engines.map(() => '---:').join(' | ')} |`);
for (const c of rubric.criteria) {
  lines.push(
    `| ${c.label}${c.hard ? ' †' : ''} | ${c.weight} | ${engines
      .map((e) => e.scores[c.id].score)
      .join(' | ')} |`,
  );
}
lines.push(
  `| **Weighted total** | **100** | ${summary.map((s) => `**${s.score}**`).join(' | ')} |`,
);
lines.push(
  `| Hard-criterion failures | | ${summary
    .map((s) => (s.hardFails.length ? `**${s.hardFails.join(', ')}**` : 'none'))
    .join(' | ')} |`,
);
lines.push('');
lines.push('† hard criterion: a 0 eliminates the engine regardless of total.');
lines.push('');
lines.push('## Measured numbers');
lines.push('');
lines.push(
  '| Engine | initial sync (2k rows) | incremental p50 | incremental p95 | replay 200 writes | heap | cold start |',
);
lines.push('| --- | ---: | ---: | ---: | ---: | ---: | ---: |');
for (const s of summary) {
  lines.push(
    `| ${s.label} | ${cell(s.initialSyncMs, 'ms')} | ${cell(s.incrementalP50Ms, 'ms')} | ${cell(
      s.incrementalP95Ms,
      'ms',
    )} | ${cell(s.replay200Ms, 'ms')} | ${cell(s.heapMb, 'MB')} | ${cell(s.coldStartMs, 'ms')} |`,
  );
}
lines.push('');
lines.push(
  '`n/m` = not measured in this spike; see `results/README.md` for why and what it would take.',
);
lines.push('');
lines.push('## Sources');
lines.push('');
for (const [k, c] of Object.entries(citations)) {
  lines.push(`- \`${k}\` — ${c.title}, ${c.date}. ${c.url}`);
}
lines.push('');

const table = lines.join('\n');
const json = `${JSON.stringify(summary, null, 2)}\n`;

if (process.argv.includes('--check')) {
  const bad = [];
  // summary.json is compared structurally so that a Biome reformat is not a false failure.
  const onDisk = JSON.parse(readFileSync(join(root, 'results/summary.json'), 'utf8'));
  if (JSON.stringify(onDisk) !== JSON.stringify(JSON.parse(json))) bad.push('results/summary.json');
  if (readFileSync(join(root, 'results/table.md'), 'utf8') !== table) bad.push('results/table.md');
  if (bad.length) {
    console.error(`stale, re-run scripts/render.mjs: ${bad.join(', ')}`);
    process.exit(1);
  }
  console.log('sync-eval: results up to date');
} else {
  writeFileSync(join(root, 'results/summary.json'), json);
  writeFileSync(join(root, 'results/table.md'), table);
  console.log('sync-eval: wrote results/summary.json and results/table.md');
}
